#!/bin/sh
# Dossier on Railway (community template, not affiliated with the Dossier project).
#
# Runs before the image's own ./start.sh (migrations, seed, server), which is
# left unchanged:
#   1. as root: hands the Railway volume (mounted root-owned) at
#      DOSSIER_DATA_DIR to the image's `node` user, then drops root for good;
#   2. turns DOSSIER_LOGIN_PASSWORD into the argon2id hash Dossier wants in
#      DOSSIER_PASSWORD and removes the plain password from the environment
#      Dossier runs with (a hash already in DOSSIER_PASSWORD wins);
#   3. waits for Postgres, so a fresh deploy doesn't fail its first migration.
set -eu

APP_USER=node
APP_HOME=/home/node
HELPERS=/app/railway
DATA_DIR=${DOSSIER_DATA_DIR:-/data}

log() { printf '[railway-entrypoint] %s\n' "$*"; }
fail() {
  printf '[railway-entrypoint] ERROR: %s\n' "$*" >&2
  exit 1
}

if [ "$(id -u)" = "0" ]; then
  mkdir -p "$DATA_DIR"
  # A Railway volume is its own filesystem; same device as / means none is attached.
  if [ "$(stat -c %d "$DATA_DIR")" = "$(stat -c %d /)" ]; then
    log "WARNING: no volume is mounted at $DATA_DIR. Nightly backups and PDF zips will be lost on every redeploy; attach a volume at $DATA_DIR."
  fi
  # Only files not yet owned by the app user are touched, so later boots just walk the tree.
  find "$DATA_DIR" -xdev \( ! -user "$APP_USER" -o ! -group "$APP_USER" \) -exec chown -h "$APP_USER:$APP_USER" {} +
  log "volume $DATA_DIR prepared; continuing as $APP_USER"
  exec setpriv --reuid="$APP_USER" --regid="$APP_USER" --init-groups \
    env HOME="$APP_HOME" USER="$APP_USER" LOGNAME="$APP_USER" "$0" "$@"
fi

# From here on the script runs without root.
if [ ! -w "$DATA_DIR" ]; then
  log "WARNING: $DATA_DIR is not writable by $(id -un); backups, imports and PDF zips will fail."
fi

# Sign-in password. Dossier refuses a plain password in DOSSIER_PASSWORD, so a
# plain one generated by the template is hashed here on every boot. The salt
# comes from DOSSIER_SECRET, so the hash (and every session) survives restarts.
provided_hash=$(printf '%s' "${DOSSIER_PASSWORD:-}" | tr -d '[:space:]')
if [ -n "$provided_hash" ]; then
  if [ -n "${DOSSIER_LOGIN_PASSWORD:-}" ]; then
    log "DOSSIER_PASSWORD is set, so DOSSIER_LOGIN_PASSWORD is ignored; delete it from the service variables."
  fi
  log "sign-in: using the hash in DOSSIER_PASSWORD"
elif [ -n "${DOSSIER_LOGIN_PASSWORD:-}" ]; then
  if ! computed_hash=$(node "$HELPERS/railway-password.mjs"); then
    fail "could not hash DOSSIER_LOGIN_PASSWORD (see the message above). Dossier was not started."
  fi
  DOSSIER_PASSWORD=$computed_hash
  export DOSSIER_PASSWORD
  log "sign-in: DOSSIER_LOGIN_PASSWORD hashed with argon2id; the plain password is not passed on to Dossier"
else
  fail "no sign-in password. Set DOSSIER_LOGIN_PASSWORD (hashed here at boot) or DOSSIER_PASSWORD (a hash from: docker run --rm -it ghcr.io/aientech/dossier hash-password)."
fi
unset DOSSIER_LOGIN_PASSWORD provided_hash computed_hash

if ! node "$HELPERS/railway-wait-db.mjs"; then
  fail "Postgres is not reachable or DATABASE_URL is wrong (see above). Railway restarts the service; check the Postgres service and DATABASE_URL."
fi

log "starting Dossier: $*"
exec "$@"
